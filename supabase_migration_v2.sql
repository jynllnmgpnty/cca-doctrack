ADD COLUMN IF NOT EXISTS claimant_relation TEXT DEFAULT 'Self',
ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT NOW();

-- Backfill user_id for existing requests by matching student_id or email with users table
UPDATE public.document_requests r
SET user_id = u.id
FROM public.users u
WHERE r.user_id IS NULL 
  AND (
    (r.student_id <> '' AND LOWER(r.student_id) = LOWER(u.student_id))
    OR (r.email <> '' AND LOWER(r.email) = LOWER(u.email))
  );

-- Backfill unique request_number for existing requests that do not have one
UPDATE public.document_requests
SET request_number = 'CCA-REQ-' || LPAD(id::TEXT, 4, '0')
WHERE request_number IS NULL OR request_number = '';

-- Ensure index and unique constraint on request_number
CREATE UNIQUE INDEX IF NOT EXISTS idx_document_requests_request_number ON public.document_requests(request_number);
CREATE INDEX IF NOT EXISTS idx_document_requests_user_id ON public.document_requests(user_id);
CREATE INDEX IF NOT EXISTS idx_document_requests_pickup_code ON public.document_requests(pickup_code);

