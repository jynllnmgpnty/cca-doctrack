CREATE INDEX IF NOT EXISTS idx_student_profiles_user_id ON public.student_profiles(user_id);
CREATE INDEX IF NOT EXISTS idx_student_profiles_student_id ON public.student_profiles(student_id);

-- Populate student_profiles from existing student accounts in users table
INSERT INTO public.student_profiles (user_id, full_name, student_id, email, course, created_at, updated_at)
SELECT u.id, u.full_name, u.student_id, u.email, u.course, u.created_at, NOW()
