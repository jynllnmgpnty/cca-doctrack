CREATE POLICY "Backend can manage request activity logs" ON public.request_activity_logs FOR ALL TO service_role USING (true);

DROP POLICY IF EXISTS "Backend can manage notifications" ON public.notifications;
CREATE POLICY "Backend can manage notifications" ON public.notifications FOR ALL TO service_role USING (true);

DROP POLICY IF EXISTS "Public can view holidays" ON public.school_holidays;
