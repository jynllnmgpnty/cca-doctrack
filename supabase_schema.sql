-- ------------------------------------------------------------------------------
-- 1. Users Table (Authentication & User Accounts)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    student_id TEXT DEFAULT '',
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    course TEXT DEFAULT 'BS Information Technology',
    role TEXT DEFAULT 'student' CHECK (role IN ('student', 'admin')),
    status TEXT DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive', 'deactivated')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_users_email ON public.users(email);
CREATE INDEX IF NOT EXISTS idx_users_student_id ON public.users(student_id);

-- ------------------------------------------------------------------------------
-- 2. Student Profiles Table (1-to-1 Relationship with users)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.student_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT UNIQUE NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    full_name TEXT NOT NULL,
    student_id TEXT NOT NULL,
    email TEXT NOT NULL,
    contact_number TEXT DEFAULT '',
    course TEXT DEFAULT 'BS Information Technology',
    year_level TEXT DEFAULT '1st Year',
    parent_guardian_name TEXT DEFAULT '',
    parent_guardian_contact TEXT DEFAULT '',
    address TEXT DEFAULT '',
    avatar TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_student_profiles_user_id ON public.student_profiles(user_id);
CREATE INDEX IF NOT EXISTS idx_student_profiles_student_id ON public.student_profiles(student_id);

-- ------------------------------------------------------------------------------
-- 3. Document Types Table (Configurable Settings, Limits, & Capacities)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.document_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    min_quantity INTEGER NOT NULL DEFAULT 1 CHECK (min_quantity > 0),
    max_quantity INTEGER NOT NULL DEFAULT 3 CHECK (max_quantity >= min_quantity),
    max_copies_per_day INTEGER NOT NULL DEFAULT 5 CHECK (max_copies_per_day > 0),
    max_pending_requests INTEGER NOT NULL DEFAULT 3 CHECK (max_pending_requests > 0),
    daily_capacity INTEGER NOT NULL DEFAULT 15 CHECK (daily_capacity > 0),
    processing_days INTEGER NOT NULL DEFAULT 2 CHECK (processing_days > 0),
    fee NUMERIC(10,2) NOT NULL DEFAULT 0.00 CHECK (fee >= 0),
    required_attachments JSONB DEFAULT '[]'::jsonb,
    material_requirements JSONB DEFAULT '[]'::jsonb,
    is_available BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 4. Document Requests Table (Core Document Request Pipeline)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.document_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    request_number TEXT UNIQUE,
    student_name TEXT NOT NULL,
    student_id TEXT NOT NULL,
    document_type TEXT NOT NULL,
    quantity INTEGER DEFAULT 1 CHECK (quantity > 0),
    purpose TEXT NOT NULL,
    date_submitted DATE NOT NULL DEFAULT CURRENT_DATE,
    status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Processing', 'For Release', 'Completed', 'Rejected')),
    course TEXT DEFAULT 'BS Information Technology',
    email TEXT DEFAULT '',
    pickup_date TEXT DEFAULT '',
    estimated_release_date DATE,
    completed_at TIMESTAMPTZ,
    rejection_reason TEXT DEFAULT '',
    pickup_code TEXT DEFAULT '',
    claimant_name TEXT DEFAULT '',
    claimant_relation TEXT DEFAULT 'Self',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_document_requests_user_id ON public.document_requests(user_id);
CREATE INDEX IF NOT EXISTS idx_document_requests_student_id ON public.document_requests(student_id);
CREATE INDEX IF NOT EXISTS idx_document_requests_status ON public.document_requests(status);
CREATE INDEX IF NOT EXISTS idx_document_requests_created_at ON public.document_requests(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_document_requests_pickup_code ON public.document_requests(pickup_code);

-- ------------------------------------------------------------------------------
-- 5. Physical Inventory Supplies Table
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name TEXT UNIQUE NOT NULL,
    description TEXT DEFAULT '',
    unit TEXT NOT NULL DEFAULT 'sheets',
    current_stock INTEGER NOT NULL DEFAULT 0 CHECK (current_stock >= 0),
    minimum_stock INTEGER NOT NULL DEFAULT 20 CHECK (minimum_stock >= 0),
    date_added TIMESTAMPTZ DEFAULT NOW(),
    last_updated TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 6. Inventory Transactions Table
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.inventory_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES public.inventory_items(id) ON DELETE CASCADE,
    change_type TEXT NOT NULL CHECK (change_type IN ('IN', 'OUT', 'ADJUSTMENT')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    previous_stock INTEGER NOT NULL CHECK (previous_stock >= 0),
    new_stock INTEGER NOT NULL CHECK (new_stock >= 0),
    reason TEXT NOT NULL DEFAULT '',
    related_request_id BIGINT REFERENCES public.document_requests(id) ON DELETE SET NULL,
    created_by TEXT NOT NULL DEFAULT 'Registrar System',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_inventory_transactions_item_id ON public.inventory_transactions(item_id);

-- ------------------------------------------------------------------------------
-- 7. Request Activity Logs (Status Transitions & Remarks)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.request_activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES public.document_requests(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    user_role TEXT DEFAULT '',
    action TEXT NOT NULL,
    previous_value TEXT DEFAULT '',
    new_value TEXT DEFAULT '',
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_request_activity_logs_request_id ON public.request_activity_logs(request_id);

-- ------------------------------------------------------------------------------
-- 8. Audit Logs Table (Immutable Security & Operation History)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    user_role TEXT DEFAULT '',
    action TEXT NOT NULL,
    affected_record TEXT DEFAULT '',
    previous_value TEXT DEFAULT '',
    new_value TEXT DEFAULT '',
    ip_address TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON public.audit_logs(created_at DESC);

-- ------------------------------------------------------------------------------
-- 9. Notifications Table
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    target_role TEXT DEFAULT '',
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    type TEXT NOT NULL DEFAULT 'info' CHECK (type IN ('info', 'request', 'status', 'inventory', 'announcement', 'warning')),
    related_request_id BIGINT REFERENCES public.document_requests(id) ON DELETE SET NULL,
    is_read BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_notifications_user_id ON public.notifications(user_id);
CREATE INDEX IF NOT EXISTS idx_notifications_is_read ON public.notifications(is_read);

-- ------------------------------------------------------------------------------
-- 10. School Holidays Table
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.school_holidays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holiday_date DATE UNIQUE NOT NULL,
    name TEXT NOT NULL,
    description TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 11. System Settings Table
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.system_settings (
    key TEXT PRIMARY KEY,
    value JSONB NOT NULL,
    description TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 12. Reactivation Requests Table
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.reactivation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id TEXT NOT NULL,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL,
    reason TEXT NOT NULL,
    status TEXT DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Rejected')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

