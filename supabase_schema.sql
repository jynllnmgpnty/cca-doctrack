DROP POLICY IF EXISTS "Backend can update requests" ON public.document_requests;
CREATE POLICY "Backend can update requests" ON public.document_requests FOR UPDATE TO service_role USING (true);

DROP POLICY IF EXISTS "Public can view inventory" ON public.inventory_items;
CREATE POLICY "Public can view inventory" ON public.inventory_items FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Backend can manage inventory" ON public.inventory_items;
CREATE POLICY "Backend can manage inventory" ON public.inventory_items FOR ALL TO service_role USING (true);
DROP POLICY IF EXISTS "Backend can manage inventory transactions" ON public.inventory_transactions;
CREATE POLICY "Backend can manage inventory transactions" ON public.inventory_transactions FOR ALL TO service_role USING (true);

DROP POLICY IF EXISTS "Backend can manage student profiles" ON public.student_profiles;
CREATE POLICY "Backend can manage student profiles" ON public.student_profiles FOR ALL TO service_role USING (true);

