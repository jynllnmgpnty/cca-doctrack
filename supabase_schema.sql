-- Idempotent Policy Setup
DROP POLICY IF EXISTS "Deny direct public anon access to users" ON public.users;
CREATE POLICY "Deny direct public anon access to users" ON public.users FOR ALL TO anon USING (false);

DROP POLICY IF EXISTS "Public can view document types" ON public.document_types;
CREATE POLICY "Public can view document types" ON public.document_types FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Backend can manage document types" ON public.document_types;
CREATE POLICY "Backend can manage document types" ON public.document_types FOR ALL TO service_role USING (true);

DROP POLICY IF EXISTS "Public can view requests" ON public.document_requests;
CREATE POLICY "Public can view requests" ON public.document_requests FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Public can submit requests" ON public.document_requests;
